/** ユーザー入力を囲むデリミタ。閉じタグの偽造を防ぐため、入力側から同名タグを除去して使う */
export function sanitizeUserText(s: string, max = 2000): string {
  return s
    .slice(0, max)
    .replace(/<\/?(verification_rule|user_note|user_appeal|system|instructions?)>/gi, "[removed]");
}

